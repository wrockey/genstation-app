struct ScrollToHelper: NSViewRepresentable {
    let trigger: Bool
    let anchor: UnitPoint
    let onComplete: () -> Void

    func makeNSView(context: Context) -> NSView {
        let v = NSView()
        v.frame.size = CGSize(width: 1, height: 1)
        return v
    }

    func updateNSView(_ nsView: NSView, context: Context) {
        guard trigger else { return }
        DispatchQueue.main.async {
            guard let scrollView = nsView.findEnclosingScrollView() else {
                onComplete()
                return
            }
            let targetRect = nsView.convert(nsView.bounds, to: scrollView.documentView)
            let visibleHeight = scrollView.contentView.bounds.height
            var offsetY = targetRect.minY
            if anchor == .top {
                offsetY = targetRect.maxY - visibleHeight
            } else if anchor == .center {
                offsetY = targetRect.midY - visibleHeight / 2
            }
            offsetY = max(0, min(offsetY, (scrollView.documentView?.bounds.height ?? 0) - visibleHeight))
            NSAnimationContext.runAnimationGroup { ctx in
                ctx.duration = 0.35
                ctx.timingFunction = CAMediaTimingFunction(name: .easeInEaseOut)
                scrollView.contentView.animator().setBoundsOrigin(NSPoint(x: 0, y: offsetY))
            }
            scrollView.reflectScrolledClipView(scrollView.contentView)
            onComplete()
        }
    }
}

private extension NSView {
    func findEnclosingScrollView() -> NSScrollView? {
        var current = superview
        while let view = current {
            if let sv = view as? NSScrollView { return sv }
            current = view.superview
        }
        return nil
    }
}
