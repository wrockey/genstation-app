// MARK: - Session Gallery View
struct SessionGalleryView: View {
    @EnvironmentObject var appState: AppState
    @Environment(\.openWindow) private var openWindow

    var onPopOut: (() -> Void)? = nil  // Optional popout action

    @State private var isExporting = false
    @State private var exportError: String?
    @State private var showExportError = false

    // Tile size control
    @State private var tileSize: CGFloat = 120
    private let minTileSize: CGFloat = 80
    private let maxTileSize: CGFloat = 300

    #if os(iOS)
    @State private var pinchScale: CGFloat = 1.0
    @State private var lastTileSize: CGFloat = 120
    #endif

    private var columns: [GridItem] {
        [GridItem(.adaptive(minimum: tileSize, maximum: tileSize), spacing: 0)]
    }

    var body: some View {
        VStack(spacing: 0) {
            if appState.ui.sessionGeneratedIDs.isEmpty {
                VStack(spacing: 12) {
                    Image(systemName: "photo.on.rectangle.angled")
                        .font(.system(size: 48))
                        .foregroundColor(.secondary.opacity(0.5))
                    Text("No images in session")
                        .font(.headline)
                        .foregroundColor(.secondary)
                    Text("Generated images will appear here")
                        .font(.subheadline)
                        .foregroundColor(.secondary.opacity(0.7))
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                #if os(macOS)
                // macOS: Slider for tile size
                HStack(spacing: 8) {
                    Image(systemName: "square.grid.4x3.fill")
                        .foregroundColor(.secondary)
                        .font(.caption)
                    Slider(value: $tileSize, in: minTileSize...maxTileSize)
                        .frame(width: 120)
                    Image(systemName: "square.grid.2x2.fill")
                        .foregroundColor(.secondary)
                        .font(.caption)
                }
                .padding(.horizontal, 12)
                .padding(.top, 8)
                .padding(.bottom, 5)
                #endif

                ScrollView {
                    LazyVGrid(columns: columns, spacing: 0) {
                        ForEach(appState.ui.sessionGeneratedIDs, id: \.self) { itemId in
                            if let item = findHistoryItem(id: itemId) {
                                SessionThumbnailView(item: item)
                                    .frame(width: tileSize, height: tileSize)
                                    .clipped()
                                    .contentShape(Rectangle())
                                    .onTapGesture {
                                        openFullHistoryItem(id: itemId)
                                    }
                                    .contextMenu {
                                        Button(role: .none) {
                                            removeFromSession(id: itemId)
                                        } label: {
                                            Label("Remove from Session", systemImage: "minus.circle")
                                        }

                                        Button(role: .destructive) {
                                            deleteFromHistory(id: itemId)
                                        } label: {
                                            Label("Delete from History", systemImage: "trash")
                                        }
                                    }
                            }
                        }
                    }
                }
                #if os(iOS)
                .simultaneousGesture(
                    MagnificationGesture()
                        .onChanged { value in
                            let newSize = lastTileSize * value
                            tileSize = min(max(newSize, minTileSize), maxTileSize)
                        }
                        .onEnded { _ in
                            lastTileSize = tileSize
                        }
                )
                #endif

                // Bottom toolbar
                HStack {
                    Button {
                        clearSession()
                    } label: {
                        Label("Clear Session", systemImage: "xmark.circle")
                    }
                    .buttonStyle(.bordered)

                    Spacer()

                    Text("\(appState.ui.sessionGeneratedIDs.count) images")
                        .font(.caption)
                        .foregroundColor(.secondary)

                    Spacer()

                    Button {
                        Task { await exportContactSheet() }
                    } label: {
                        if isExporting {
                            ProgressView()
                                .scaleEffect(0.7)
                        } else {
                            Label("Export Sheet", systemImage: "square.grid.2x2")
                        }
                    }
                    .buttonStyle(.bordered)
                    .disabled(appState.ui.sessionGeneratedIDs.isEmpty || isExporting)

                    // Popout button (when provided)
                    if let onPopOut = onPopOut {
                        Button(action: onPopOut) {
                            Image(systemName: "arrow.up.forward.square")
                        }
                        .buttonStyle(.borderedProminent)
                        .tint(.blue)
