// MARK: - Scroll-to-visible helper (bypasses ScrollViewReader bugs on iOS)

#if os(iOS)
struct ScrollToHelper: UIViewRepresentable {
    let trigger: Bool
    let anchor: UnitPoint
    let onComplete: () -> Void

    func makeUIView(context: Context) -> UIView {
        let v = UIView()
        v.backgroundColor = .clear
        v.isUserInteractionEnabled = false
        v.frame.size = CGSize(width: 1, height: 1)
        return v
    }

    func updateUIView(_ uiView: UIView, context: Context) {
        guard trigger else { return }
        DispatchQueue.main.async {
            guard let scrollView = uiView.findEnclosingScrollView() else {
                onComplete()
                return
            }
            let targetRect = uiView.convert(uiView.bounds, to: scrollView)
            let visibleHeight = scrollView.bounds.height - scrollView.adjustedContentInset.top - scrollView.adjustedContentInset.bottom
            var offsetY = targetRect.minY - scrollView.adjustedContentInset.top
            if anchor == .center {
                offsetY -= (visibleHeight - targetRect.height) / 2
            } else if anchor == .bottom {
                offsetY -= visibleHeight - targetRect.height
            }
            offsetY = max(0, min(offsetY, scrollView.contentSize.height - scrollView.bounds.height + scrollView.adjustedContentInset.bottom))
            UIView.animate(withDuration: 0.35, delay: 0, options: [.curveEaseInOut, .allowUserInteraction]) {
                scrollView.contentOffset = CGPoint(x: scrollView.contentOffset.x, y: offsetY)
            }
            onComplete()
        }
    }
}

private extension UIView {
    func findEnclosingScrollView() -> UIScrollView? {
        var current = superview
        while let view = current {
            if let sv = view as? UIScrollView { return sv }
            current = view.superview
        }
        return nil
    }
}

