extension Binding where Value == Bool {
    var not: Binding<Bool> {
        Binding<Bool>(
            get: { !self.wrappedValue },
            set: { self.wrappedValue = !$0 }
        )
    }
}
extension Int {
    /// Returns the smallest multiple of `multiple` that is ≥ self
    func nextMultipleOf(_ multiple: Int) -> Int {
        guard multiple != 0 else { return self }
        let remainder = self % multiple
        guard remainder != 0 else { return self }
        return self + (multiple - remainder)
    }
}

