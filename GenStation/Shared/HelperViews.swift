// MARK: - Liquid Glass Toast Component
/// A reusable toast notification with frosted glass appearance.
/// Use this throughout the app for consistent toast styling.
struct LiquidGlassToast: View {
    let message: String
    let icon: String
    let tint: Color
    let actionLabel: String?
    let action: (() -> Void)?

    /// Creates a toast with automatic icon and tint based on message content
    init(message: String) {
        self.message = message
        self.icon = LiquidGlassToast.autoIcon(for: message)
        self.tint = LiquidGlassToast.autoTint(for: message)
        self.actionLabel = nil
        self.action = nil
    }

    /// Creates a toast with custom icon and tint
    init(message: String, icon: String, tint: Color) {
        self.message = message
        self.icon = icon
        self.tint = tint
        self.actionLabel = nil
        self.action = nil
    }

    /// Creates a toast with an action button (e.g., Undo)
    init(message: String, actionLabel: String = "Undo", action: @escaping () -> Void) {
        self.message = message
        self.icon = LiquidGlassToast.autoIcon(for: message)
        self.tint = LiquidGlassToast.autoTint(for: message)
        self.actionLabel = actionLabel
        self.action = action
    }

    /// Creates a toast with custom styling and an action button
    init(message: String, icon: String, tint: Color, actionLabel: String, action: @escaping () -> Void) {
        self.message = message
        self.icon = icon
        self.tint = tint
        self.actionLabel = actionLabel
        self.action = action
    }

    var body: some View {
        HStack(spacing: 10) {
            Image(systemName: icon)
                .font(.system(size: 16, weight: .semibold))
                .foregroundStyle(tint)
            Text(message)
                .font(.system(size: 15, weight: .medium))
                .foregroundStyle(.primary)

            if let actionLabel = actionLabel, let action = action {
                Divider()
                    .frame(height: 20)
                    .opacity(0.5)

                Button(action: action) {
                    Text(actionLabel)
                        .font(.system(size: 15, weight: .semibold))
                        .foregroundStyle(.blue)
                }
                .buttonStyle(.plain)
                #if os(iOS)
                .hoverEffect(.lift)
                #endif
            }
        }
        .padding(.horizontal, 18)
        .padding(.vertical, 12)
        .background(.ultraThinMaterial, in: Capsule())
        .overlay(Capsule().strokeBorder(.quaternary.opacity(0.3), lineWidth: 0.5))
        .shadow(color: .black.opacity(0.12), radius: 12, y: 4)
    }

    /// Automatically determines the appropriate icon based on message content
    static func autoIcon(for message: String) -> String {
        let lower = message.lowercased()
        if lower.contains("copied") || lower.contains("clipboard") { return "doc.on.doc.fill" }
        if lower.contains("saved") || lower.contains("save") { return "checkmark.circle.fill" }
        if lower.contains("added") { return "plus.circle.fill" }
        if lower.contains("removed") || lower.contains("cleared") { return "minus.circle.fill" }
        if lower.contains("moved") { return "folder.fill" }
        if lower.contains("failed") || lower.contains("error") { return "exclamationmark.triangle.fill" }
        if lower.contains("deleted") || lower.contains("delete") { return "trash.fill" }
        if lower.contains("selection") || lower.contains("selected") { return "checkmark.circle.fill" }
        if lower.contains("export") || lower.contains("compressing") { return "square.and.arrow.up.fill" }
        if lower.contains("import") || lower.contains("extracting") { return "square.and.arrow.down.fill" }
        if lower.contains("loading") || lower.contains("preparing") { return "hourglass" }
        if lower.contains("undo") { return "arrow.uturn.backward.circle.fill" }
        if lower.contains("redo") { return "arrow.uturn.forward.circle.fill" }
        if lower.contains("photo") { return "photo.fill" }
        if lower.contains("input") { return "photo.on.rectangle.angled" }
        if lower.contains("folder") { return "folder.fill" }
        return "info.circle.fill"
    }

    /// Automatically determines the appropriate tint color based on message content
    static func autoTint(for message: String) -> Color {
        let lower = message.lowercased()
        if lower.contains("copied") || lower.contains("clipboard") { return .blue }
        if lower.contains("saved") || lower.contains("added") || lower.contains("success") || lower.contains("ready") { return .green }
        if lower.contains("removed") || lower.contains("cleared") { return .orange }
        if lower.contains("moved") { return .purple }
        if lower.contains("failed") || lower.contains("error") { return .red }
        if lower.contains("deleted") || lower.contains("delete") { return .red }
        if lower.contains("selection") || lower.contains("selected") { return .blue }
        if lower.contains("export") || lower.contains("import") { return .blue }
        if lower.contains("loading") || lower.contains("preparing") || lower.contains("extracting") || lower.contains("compressing") { return .secondary }
        if lower.contains("undo") || lower.contains("redo") { return .blue }
        if lower.contains("photo") || lower.contains("input") { return .green }
        if lower.contains("folder") { return .purple }
        return .secondary
    }
}

/// Standard toast transition with spring animation for entrance and quick fade for exit
extension AnyTransition {
    static var toastTransition: AnyTransition {
        .asymmetric(
            insertion: .scale(scale: 0.8).combined(with: .opacity).animation(.spring(response: 0.35, dampingFraction: 0.7)),
            removal: .opacity.animation(.easeOut(duration: 0.2))
        )
    }
}

