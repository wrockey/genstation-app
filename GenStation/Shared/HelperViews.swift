    private func performOnboardingGeneration(prompt: String) async throws -> PlatformImage {
        // Use Gemini if available (simplest API)
        if !appState.settings.apiKey.isEmpty {
            return try await generateWithGemini(prompt: prompt)
        }
        // Fallback to AI/ML API
        else if !appState.settings.aimlapiKey.isEmpty {
            return try await generateWithAIMLAPI(prompt: prompt)
        }
        // Fallback to Grok
        else if !appState.settings.grokApiKey.isEmpty {
            return try await generateWithGrok(prompt: prompt)
        }

        throw NSError(domain: "Onboarding", code: 1, userInfo: [NSLocalizedDescriptionKey: "No API key configured"])
    }

    private func generateWithGemini(prompt: String) async throws -> PlatformImage {
        let modelName = "gemini-2.0-flash-exp-image-generation"
        let url = GeminiClient.generateContentURL(model: modelName, apiKey: appState.settings.apiKey)

        var request = URLRequest(url: url)
        request.httpMethod = "POST"
        request.addValue("application/json", forHTTPHeaderField: "Content-Type")

        let body: [String: Any] = [
            "contents": [["parts": [["text": prompt]]]],
            "generationConfig": ["responseModalities": ["TEXT", "IMAGE"]]
        ]
        request.httpBody = try JSONSerialization.data(withJSONObject: body)

        let (data, _) = try await URLSession.shared.data(for: request)

        guard let json = try JSONSerialization.jsonObject(with: data) as? [String: Any],
              let candidates = json["candidates"] as? [[String: Any]],
              let content = candidates.first?["content"] as? [String: Any],
              let parts = content["parts"] as? [[String: Any]] else {
            throw NSError(domain: "Onboarding", code: 3, userInfo: [NSLocalizedDescriptionKey: "Invalid response"])
        }

        for part in parts {
            if let inlineData = part["inlineData"] as? [String: Any],
               let base64String = inlineData["data"] as? String,
               let imageData = Data(base64Encoded: base64String) {
                #if os(macOS)
                if let image = NSImage(data: imageData) { return image }
                #else
                if let image = UIImage(data: imageData) { return image }
                #endif
            }
        }

        throw NSError(domain: "Onboarding", code: 4, userInfo: [NSLocalizedDescriptionKey: "No image in response"])
    }

    private func generateWithAIMLAPI(prompt: String) async throws -> PlatformImage {
        // Use v1 endpoint with DALL-E 3 for reliable sync response
        let url = AIMLEndpoints.imagesGenerationsURL

        var request = URLRequest(url: url)
        request.httpMethod = "POST"
        request.addValue("application/json", forHTTPHeaderField: "Content-Type")
        request.addValue("Bearer \(appState.settings.aimlapiKey)", forHTTPHeaderField: "Authorization")

        let body: [String: Any] = [
            "model": "dall-e-3",
            "prompt": prompt,
            "size": "1024x1024",
            "n": 1
        ]
        request.httpBody = try JSONSerialization.data(withJSONObject: body)

        let (data, _) = try await URLSession.shared.data(for: request)

        // Parse OpenAI-style response format: { "data": [{ "url": "..." }] }
        guard let json = try JSONSerialization.jsonObject(with: data) as? [String: Any],
              let dataArray = json["data"] as? [[String: Any]],
              let imageInfo = dataArray.first else {
            // Check for error message
            if let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
               let error = json["error"] as? [String: Any],
               let message = error["message"] as? String {
                throw NSError(domain: "Onboarding", code: 3, userInfo: [NSLocalizedDescriptionKey: message])
            }
            throw NSError(domain: "Onboarding", code: 3, userInfo: [NSLocalizedDescriptionKey: "Invalid response"])
        }

        // Handle URL or base64 response
        if let imageUrlString = imageInfo["url"] as? String,
           let imageUrl = URL(string: imageUrlString) {
            let (imageData, _) = try await URLSession.shared.data(from: imageUrl)
            #if os(macOS)
            if let image = NSImage(data: imageData) { return image }
            #else
            if let image = UIImage(data: imageData) { return image }
            #endif
        } else if let b64String = imageInfo["b64_json"] as? String,
                  let imageData = Data(base64Encoded: b64String) {
            #if os(macOS)
            if let image = NSImage(data: imageData) { return image }
            #else
            if let image = UIImage(data: imageData) { return image }
            #endif
        }

        throw NSError(domain: "Onboarding", code: 4, userInfo: [NSLocalizedDescriptionKey: "Failed to load image"])
    }

    private func generateWithGrok(prompt: String) async throws -> PlatformImage {
        var request = URLRequest(url: GrokClient.imageGenerationsURL)
        request.httpMethod = "POST"
        request.addValue("application/json", forHTTPHeaderField: "Content-Type")
        let auth = GrokClient.authorizationHeader(apiKey: appState.settings.grokApiKey)
        request.addValue(auth.value, forHTTPHeaderField: auth.name)

        let body: [String: Any] = [
            // grok-2-image is no longer served by x.ai (audit 2026-07-01).
            "model": "grok-imagine-image",
            "prompt": prompt
        ]
        request.httpBody = try JSONSerialization.data(withJSONObject: body)

        let (data, _) = try await URLSession.shared.data(for: request)

        guard let json = try JSONSerialization.jsonObject(with: data) as? [String: Any],
              let dataArray = json["data"] as? [[String: Any]],
              let imageInfo = dataArray.first,
              let base64String = imageInfo["b64_json"] as? String,
              let imageData = Data(base64Encoded: base64String) else {
            throw NSError(domain: "Onboarding", code: 3, userInfo: [NSLocalizedDescriptionKey: "Invalid response"])
        }

        #if os(macOS)
        if let image = NSImage(data: imageData) { return image }
        #else
        if let image = UIImage(data: imageData) { return image }
        #endif

        throw NSError(domain: "Onboarding", code: 4, userInfo: [NSLocalizedDescriptionKey: "Failed to decode image"])
    }

