struct KeyboardDoneAccessory: UIViewRepresentable {
    let onDone: () -> Void

    func makeUIView(context: Context) -> UIView {
        let v = UIView(frame: .zero)
        v.backgroundColor = .clear
        v.isUserInteractionEnabled = false
        DispatchQueue.main.async {
            Self.attachAccessory(to: v, onDone: onDone)
        }
        return v
    }

    func updateUIView(_ uiView: UIView, context: Context) {}

    private static func attachAccessory(to view: UIView, onDone: @escaping () -> Void) {
        // Walk up to find the nearest UITextView among ancestors' subviews
        guard let textView = findTextViewNear(view) else { return }
        guard textView.inputAccessoryView == nil else { return }

        let toolbar = UIToolbar(frame: CGRect(x: 0, y: 0, width: UIScreen.main.bounds.width, height: 44))
        toolbar.sizeToFit()
        let spacer = UIBarButtonItem(barButtonSystemItem: .flexibleSpace, target: nil, action: nil)
        let done = UIBarButtonItem(title: "Done", style: .done, target: nil, action: #selector(DoneHelper.dismiss))
        DoneHelper.shared.onDone = onDone
        done.target = DoneHelper.shared
        toolbar.items = [spacer, done]
        textView.inputAccessoryView = toolbar
        textView.reloadInputViews()
    }

    /// Walk up the view hierarchy and at each level do a shallow search of children for a UITextView.
    private static func findTextViewNear(_ view: UIView) -> UITextView? {
        var current: UIView? = view.superview
        var depth = 0
        while let parent = current, depth < 15 {
            if let tv = shallowFindTextView(in: parent) { return tv }
            current = parent.superview
            depth += 1
        }
        return nil
    }

    /// Breadth-first search for UITextView, max 3 levels deep to avoid runaway traversal.
    private static func shallowFindTextView(in view: UIView, maxDepth: Int = 3) -> UITextView? {
        if let tv = view as? UITextView { return tv }
        guard maxDepth > 0 else { return nil }
        for sub in view.subviews {
            if let tv = shallowFindTextView(in: sub, maxDepth: maxDepth - 1) { return tv }
        }
        return nil
    }
}

private class DoneHelper: NSObject {
    static let shared = DoneHelper()
    var onDone: (() -> Void)?

    @objc func dismiss() {
        onDone?()
    }
}

