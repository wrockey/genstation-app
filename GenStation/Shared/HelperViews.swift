struct LoadingView: View {
    let mode: Provider
    let progress: Double
    let progressStep: Int
    let progressMax: Int
    let currentNodeName: String?
    let isCancelled: Binding<Bool>
    let onStop: () -> Void
    var batchTotal: Int = 0
    var batchCurrent: Int = 0
    /// Set for AIML video mode: shows elapsed + typical range + provider status
    /// for the queue's active jobs (batch video runs still block on this view).
    var videoJobQueue: JobQueue? = nil

    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @State private var startDate = Date()

    var body: some View {
        VStack(spacing: 20) {
            // Batch progress (when running a batch)
            if batchTotal > 0 {
                VStack(spacing: 8) {
                    Text("Generating \(min(batchCurrent + 1, batchTotal)) of \(batchTotal)")
                        .font(DS.bodyFont.weight(.semibold))
                        .foregroundColor(.primary)

                    ProgressView(value: Double(batchCurrent), total: Double(batchTotal))
                        .progressViewStyle(LinearProgressViewStyle())
                        .tint(.accentColor)
                        .frame(maxWidth: .infinity)
                }
            }

            // Primary loading indicator — respect Reduce Motion accessibility setting
            if reduceMotion {
                ProgressView()
                    .controlSize(.large)
            } else {
                AbstractBloomExpansionLoading()
                    .frame(width: 200, height: 100)
            }

            // Mode-specific progress details
            if mode == .comfyUI {
                VStack(spacing: 8) {
                    if progressMax > 0 {
                        Text("Step \(progressStep)/\(progressMax)")
                            .font(.headline)
                            .foregroundColor(.primary)
                    }

                    if let nodeName = currentNodeName {
                        Text(nodeName)
                            .font(.subheadline)
                            .foregroundColor(.secondary)
                            .lineLimit(1)
                    }

                    ProgressView(value: progress)
                        .progressViewStyle(LinearProgressViewStyle())
                        .frame(maxWidth: .infinity)
                }
            } else if batchTotal == 0 {
                Text(statusText)
                    .font(.subheadline)
                    .foregroundColor(.secondary)
            }

            // Remote video jobs: elapsed + per-model typical range + provider status
            if let queue = videoJobQueue {
                VideoJobProgressView(queue: queue)
            }

            // Elapsed time (appears after 10s to reassure the user)
            TimelineView(.periodic(from: startDate, by: 1)) { context in
                let elapsed = Int(context.date.timeIntervalSince(startDate))
                if elapsed >= 10 {
                    Text("Elapsed: \(elapsed)s")
                        .font(.caption)
                        .foregroundColor(.secondary)
                }
            }

            Button(batchTotal > 0 ? "Cancel Batch" : "Stop") {
                isCancelled.wrappedValue = true
                onStop()
            }
            .buttonStyle(.borderedProminent)
            .tint(.red)
        }
        .padding()
    }

    private var statusText: String {
        switch mode {
        case .gemini: return "Sending to Gemini…"
        case .grok: return "Sending to Grok…"
        case .aimlapi: return "Sending to AI/ML API…"
        case .comfyUI: return "Processing workflow…"
        }
    }
}

