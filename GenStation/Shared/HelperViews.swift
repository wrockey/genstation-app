    private func updateWindowSize() {
        #if os(macOS)
        let index = appState.ui.currentOutputIndex
        guard index < appState.ui.outputImages.count,
              let window = NSApp.windows.last(where: { $0.identifier?.rawValue.contains("response-window") ?? false })
              ?? NSApp.windows.last, // fallback
              let screen = NSScreen.main else {
            return
        }

        let textHeight: CGFloat = 100 // slightly more room for prompt
        let minWidth: CGFloat = 1000   // ← much more reasonable minimum
        let minHeight: CGFloat = 700

        var desiredSize: CGSize

        if let optionalPath = appState.ui.outputPaths[safe: index],
           let path = optionalPath,
           path.hasSuffix(".mp4"),
           isVideoPlayable {
            desiredSize = CGSize(width: max(videoAspectRatio * 600, minWidth), height: 600 + textHeight)
        } else if let platformImage = appState.ui.outputImages[index] {
            let imageSize = platformImage.platformSize
            desiredSize = CGSize(width: max(imageSize.width, minWidth),
                                 height: imageSize.height + textHeight)
        } else {
            // This case runs on first open → make it large from the start
            desiredSize = CGSize(width: 1200, height: 800)
        }

        let screenSize = screen.visibleFrame.size
        let margin: CGFloat = 100

        // Ensure maxSize is never negative or zero
        let maxSize = CGSize(width: max(200, screenSize.width - margin),
                             height: max(200, screenSize.height - margin))

        // Guard against division by zero/negative
        let safeDesiredWidth = max(1, desiredSize.width)
        let safeDesiredHeight = max(1, desiredSize.height)
        let scale = min(1.0, min(maxSize.width / safeDesiredWidth, maxSize.height / safeDesiredHeight))
        let finalSize = CGSize(width: desiredSize.width * scale, height: desiredSize.height * scale)

        // Respect user resize, but enforce minimum
        let currentSize = window.frame.size
        if currentSize.width < minWidth || currentSize.height < minHeight {
            window.setContentSize(finalSize)
            window.center()
        } else {
            // Optional: only grow, never shrink below current user size
            window.setContentSize(CGSize(width: max(currentSize.width, finalSize.width),
                                         height: max(currentSize.height, finalSize.height)))
        }
        #endif
    }
   
    private func loadVideoMetadataAndPlayer() async {
        let index = appState.ui.currentOutputIndex
        guard let optionalPath = appState.ui.outputPaths[safe: index],
              let path = optionalPath,
              path.hasSuffix(".mp4") else {
            isVideoPlayable = false
            videoAspectRatio = 16.0 / 9.0
            player = nil
            return
        }
       
        let fileURL = URL(fileURLWithPath: path)
        guard fileExists(path: path) else {
            isVideoPlayable = false
            videoAspectRatio = 16.0 / 9.0
            player = nil
            return
        }
       
        if let dir = appState.settings.outputDirectory {
            let didStart = dir.startAccessingSecurityScopedResource()
            if didStart {
                defer { dir.stopAccessingSecurityScopedResource() }
                await loadMetadataAndPlayer(from: fileURL)
            } else {
                Log.debug("Failed to start security scope for dir: \(dir.path)")
                isVideoPlayable = false
                videoAspectRatio = 16.0 / 9.0
                player = nil
            }
        } else {
            await loadMetadataAndPlayer(from: fileURL)
        }
    }
   
    private func loadMetadataAndPlayer(from fileURL: URL) async {
        let asset = AVAsset(url: fileURL)
        do {
            let isPlayable = try await asset.load(.isPlayable)
            guard isPlayable else {
                isVideoPlayable = false
                videoAspectRatio = 16.0 / 9.0
                player = nil
                return
            }
            let tracks = try await asset.loadTracks(withMediaType: .video)
            let naturalSize = try await tracks.first?.load(.naturalSize) ?? CGSize(width: 16, height: 9)
            isVideoPlayable = true
            videoAspectRatio = naturalSize.width / naturalSize.height
            player = AVPlayer(url: fileURL)
        } catch {
            Log.debug("Failed to load video metadata: \(error)")
            isVideoPlayable = false
            videoAspectRatio = 16.0 / 9.0
            player = nil
        }
    }
   
    private func fileExists(path: String) -> Bool {
