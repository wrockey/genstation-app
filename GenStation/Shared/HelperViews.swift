        } message: {
            Text(exportError ?? "Unknown error")
        }
    }

    // MARK: - Helper Functions

    private func findHistoryItem(id: UUID) -> HistoryItem? {
        return findItemRecursive(id: id, in: appState.historyState.history)
    }

    private func findItemRecursive(id: UUID, in entries: [HistoryEntry]) -> HistoryItem? {
        for entry in entries {
            switch entry {
            case .item(let item):
                if item.id == id { return item }
            case .folder(let folder):
                if let found = findItemRecursive(id: id, in: folder.children) {
                    return found
                }
            }
        }
        return nil
    }

    private func openFullHistoryItem(id: UUID) {
        #if os(iOS)
        appState.presentedModal = .fullHistoryItem(id)
        #elseif os(macOS)
        openWindow(id: "history-viewer", value: id)
        #endif
    }

    private func removeFromSession(id: UUID) {
        appState.ui.sessionGeneratedIDs.removeAll { $0 == id }
        appState.ui.objectWillChange.send()
    }

    private func deleteFromHistory(id: UUID) {
        // Remove from session
        removeFromSession(id: id)
        // Remove from history
        deleteItemRecursive(id: id, from: &appState.historyState.history)
        appState.historyState.saveHistory()
        appState.historyState.objectWillChange.send()
    }

    private func deleteItemRecursive(id: UUID, from entries: inout [HistoryEntry]) {
        entries.removeAll { entry in
            if case .item(let item) = entry, item.id == id {
                // Also delete the file
                if let path = item.imagePath {
                    try? FileManager.default.removeItem(atPath: path)
                }
                return true
            }
            return false
        }
        // Recurse into folders
        for i in entries.indices {
            if case .folder(var folder) = entries[i] {
                deleteItemRecursive(id: id, from: &folder.children)
                entries[i] = .folder(folder)
            }
        }
    }

    private func clearSession() {
        appState.ui.sessionGeneratedIDs.removeAll()
        appState.ui.objectWillChange.send()
    }

    private func exportContactSheet() async {
        guard !appState.ui.sessionGeneratedIDs.isEmpty else { return }

        await MainActor.run { isExporting = true }
        defer { Task { @MainActor in isExporting = false } }

        // Collect items
        var items: [HistoryItem] = []
        for id in appState.ui.sessionGeneratedIDs {
            if let item = findHistoryItem(id: id) {
                items.append(item)
            }
        }

        guard !items.isEmpty else {
            await MainActor.run {
                exportError = "No valid items to export"
                showExportError = true
            }
            return
        }

        // Load full images for each item
        var images: [PlatformImage] = []
        for item in items {
            if let image = await LazyThumbnailView.loadFullImage(for: item, appState: appState) {
                images.append(image)
            } else if let thumbnail = await LazyThumbnailView.loadThumbnail(for: item, appState: appState) {
                // Fallback to thumbnail if full image unavailable
                images.append(thumbnail)
            }
        }

        guard !images.isEmpty else {
            await MainActor.run {
                exportError = "Could not load any images"
                showExportError = true
            }
            return
        }

        // Create contact sheet
        let gridColumns = min(4, Int(ceil(sqrt(Double(images.count)))))
        let gridRows = Int(ceil(Double(images.count) / Double(gridColumns)))
        let tileSize: CGFloat = 512
        let spacing: CGFloat = 8
        let padding: CGFloat = 16

        let totalWidth = padding * 2 + CGFloat(gridColumns) * tileSize + CGFloat(gridColumns - 1) * spacing
        let totalHeight = padding * 2 + CGFloat(gridRows) * tileSize + CGFloat(gridRows - 1) * spacing

        #if os(macOS)
        let contactSheet = NSImage(size: NSSize(width: totalWidth, height: totalHeight))
        contactSheet.lockFocus()

        // Fill background
        NSColor.windowBackgroundColor.setFill()
        NSRect(x: 0, y: 0, width: totalWidth, height: totalHeight).fill()

        for (index, image) in images.enumerated() {
            let col = index % gridColumns
            let row = index / gridColumns
            let x = padding + CGFloat(col) * (tileSize + spacing)
            let y = totalHeight - padding - CGFloat(row + 1) * tileSize - CGFloat(row) * spacing

            // Draw image scaled to fit
            let imageSize = image.size
            let scale = min(tileSize / imageSize.width, tileSize / imageSize.height)
            let scaledWidth = imageSize.width * scale
            let scaledHeight = imageSize.height * scale
            let drawX = x + (tileSize - scaledWidth) / 2
            let drawY = y + (tileSize - scaledHeight) / 2

            image.draw(in: NSRect(x: drawX, y: drawY, width: scaledWidth, height: scaledHeight),
                       from: NSRect(origin: .zero, size: imageSize),
                       operation: .sourceOver,
                       fraction: 1.0)
        }

        contactSheet.unlockFocus()

        // Save dialog
        await MainActor.run {
            let savePanel = NSSavePanel()
            savePanel.allowedContentTypes = [.png]
            savePanel.nameFieldStringValue = "ContactSheet_\(DateFormatter.localizedString(from: Date(), dateStyle: .short, timeStyle: .none).replacingOccurrences(of: "/", with: "-")).png"

            if savePanel.runModal() == .OK, let url = savePanel.url {
                if let pngData = contactSheet.pngData() {
                    do {
                        try pngData.write(to: url)
                        Log.debug("Contact sheet saved to: \(url.path)")
                    } catch {
                        exportError = "Failed to save: \(error.localizedDescription)"
                        showExportError = true
                    }
                }
            }
        }

        #elseif os(iOS)
        let format = UIGraphicsImageRendererFormat()
        format.scale = 1.0
        let renderer = UIGraphicsImageRenderer(size: CGSize(width: totalWidth, height: totalHeight), format: format)

        let contactSheet = renderer.image { context in
            // Fill background
            UIColor.systemBackground.setFill()
            context.fill(CGRect(x: 0, y: 0, width: totalWidth, height: totalHeight))

            for (index, image) in images.enumerated() {
                let col = index % gridColumns
                let row = index / gridColumns
                let x = padding + CGFloat(col) * (tileSize + spacing)
                let y = padding + CGFloat(row) * (tileSize + spacing)

                // Draw image scaled to fit
                let imageSize = image.size
                let scale = min(tileSize / imageSize.width, tileSize / imageSize.height)
                let scaledWidth = imageSize.width * scale
                let scaledHeight = imageSize.height * scale
                let drawX = x + (tileSize - scaledWidth) / 2
                let drawY = y + (tileSize - scaledHeight) / 2

                image.draw(in: CGRect(x: drawX, y: drawY, width: scaledWidth, height: scaledHeight))
            }
        }

        // Present share sheet
        await MainActor.run {
            let activityVC = UIActivityViewController(activityItems: [contactSheet], applicationActivities: nil)

            if let popover = activityVC.popoverPresentationController {
                popover.sourceView = UIView()
                popover.sourceRect = CGRect(x: UIScreen.main.bounds.midX,
                                            y: UIScreen.main.bounds.midY,
                                            width: 0, height: 0)
                popover.permittedArrowDirections = []
            }

            let keyWindow = UIApplication.shared.connectedScenes
                .compactMap { $0 as? UIWindowScene }
                .flatMap { $0.windows }
                .first(where: { $0.isKeyWindow })

            var topVC = keyWindow?.rootViewController
            while let presented = topVC?.presentedViewController {
                topVC = presented
            }
            topVC?.present(activityVC, animated: true)
        }
        #endif
    }
}

// MARK: - Session Thumbnail View
struct SessionThumbnailView: View {
    let item: HistoryItem
    @EnvironmentObject var appState: AppState
    @State private var thumbnail: PlatformImage?

    var body: some View {
        ZStack {
            if let thumbnail = thumbnail {
                Image(platformImage: thumbnail)
                    .resizable()
                    .aspectRatio(contentMode: .fill)
            } else {
                Rectangle()
                    .fill(Color.secondary.opacity(0.2))
                    .overlay(
                        ProgressView()
                            .scaleEffect(0.7)
                    )
            }
        }
        .task(id: HistoryThumbnailSource(item)) {
            thumbnail = nil
            let loaded = await LazyThumbnailView.loadThumbnail(for: item, appState: appState)
            guard !Task.isCancelled else { return }
            thumbnail = loaded
        }
    }
}

