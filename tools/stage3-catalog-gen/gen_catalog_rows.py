#!/usr/bin/env python3
"""Stage 3 Task 8 — emit one CatalogModel row per registered AI/ML id.

STRICT: any construct this does not understand raises SystemExit naming the source line.
Run from the repository root:

    python3 tools/stage3-catalog-gen/gen_catalog_rows.py
"""
import os
import re

REG = "GenStation/Catalog/ModelRegistry.swift"
OUTDIR = "Packages/GenStationCore/Sources/GenStationCore/Catalog/Models"

# The ONE id-dependent group (ModelRegistry.swift:1876). Any other local binding aborts.
ID_PREDICATE = 'let isGPTImage2 = id.lowercased().hasSuffix("gpt-image-2")'

FIELDS = ["id", "isI2I", "maxInputImages", "imageInputParam", "secondImageParam",
          "acceptsMultiImages", "acceptsBase64", "acceptsPublicURL", "acceptsBinary",
          "isVideo", "generationEndpoint", "pollingEndpoint", "requiresInputImage",
          "supportsMask"]
# Defaulted in AIMLModel.init (ModelRegistry.swift:30, :33): absent means this value.
DEFAULTS = {"secondImageParam": None, "supportsMask": False}
ENDPOINTS = {"AIMLEndpoints.imageGeneration", "AIMLEndpoints.videoGeneration",
             "AIMLEndpoints.videoGenerationPoll", "AIMLEndpoints.klingGeneration",
             "AIMLEndpoints.klingGenerationPoll"}

# Vendor token (first "/"-separated component of the first slashed id in the group) -> the
# vendor name used in the emitted file name. Mirrors Params/Tables/.
VENDORS = {
    "alibaba": "Alibaba", "blackforestlabs": "BlackForestLabs", "flux": "BlackForestLabs",
    "bytedance": "ByteDance", "google": "Google", "veo2": "Google", "hunyuan": "Tencent",
    "klingai": "Kling", "kling-video": "Kling", "openai": "OpenAI", "reve": "Reve",
    "topaz-labs": "Topaz", "x-ai": "XAI", "kandinsky5": "Kandinsky", "ltxv": "Lightricks",
    "ltxv-2": "Lightricks", "luma": "Luma", "minimax": "Minimax", "pixverse": "PixVerse",
    "runway": "Runway",
}
# The five groups whose ids carry no "/" at all, so no vendor token can be read off them.
NO_SLASH_VENDORS = {
    "flux-realism": "BlackForestLabs", "flux-pro": "BlackForestLabs", "recraft-v3": "Recraft",
    "stable-diffusion-v35-large": "StabilityAI", "stable-diffusion-v3-medium": "StabilityAI",
}


def die(lineno, msg):
    raise SystemExit("ABORT %s:%d — %s" % (REG, lineno, msg))


def strip_comment(line):
    return line.split("//")[0] if "//" in line else line


def parse_value(raw, lineno, group, is_gpt2):
    """Literal forms only. `is_gpt2` is None outside the one id-dependent group."""
    v = raw.strip()
    if v == "true":
        return True
    if v == "false":
        return False
    if v == "nil":
        return None
    if v == "id":
        return "<id>"
    if re.fullmatch(r"-?\d+", v):
        return int(v)
    if re.fullmatch(r'"[^"]*"', v):
        return v[1:-1]
    if v in ENDPOINTS:
        return ("endpoint", v)
    if is_gpt2 is not None:
        if v == "isGPTImage2":
            return is_gpt2
        m = re.fullmatch(r"isGPTImage2 \? (\d+) : (\d+)", v)
        if m:
            return int(m.group(1)) if is_gpt2 else int(m.group(2))
    die(lineno, "reg(%s): value %r is not a literal this generator understands" % (group, v))


def split_args(text, lineno, group):
    """Top-level comma split. Aborts on any nesting — the registry has none."""
    if "(" in text or ")" in text:
        die(lineno, "reg(%s): nested parentheses in the AIMLModel argument list" % group)
    return [p for p in (p.strip() for p in text.split(",")) if p]


def file_stem(ids, is_video, lineno):
    """Which per-vendor file this GROUP's rows go in — one file per group, so an alias
    never lands apart from its canonical even when their spellings disagree."""
    token = None
    for mid in ids:
        if "/" in mid:
            token = mid.split("/")[0].lower()
            break
    if token is None:
        vendor = NO_SLASH_VENDORS.get(ids[0].lower())
        if vendor is None:
            die(lineno, "reg(%s): no id carries a '/' and the group is not in NO_SLASH_VENDORS"
                % ids[0])
    else:
        vendor = VENDORS.get(token)
        if vendor is None:
            die(lineno, "reg(%s): unmapped vendor token %r — add it to VENDORS" % (ids[0], token))
    return ("Video" if is_video else "Image") + vendor + "Rows"


def swift_lit(v):
    if v is True:
        return "true"
    if v is False:
        return "false"
    if v is None:
        return "nil"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, tuple):      # an AIMLEndpoints member: emit the reference, not the string
        return v[1]
    return '"%s"' % v


def swift_property(stem):
    return stem[0].lower() + stem[1:]


HEADER = """\
// %s — generated CatalogModel rows for %s.
//
// GENERATED by tools/stage3-catalog-gen/gen_catalog_rows.py from
// GenStation/Catalog/ModelRegistry.swift's reg() blocks. Do not hand-edit: the generator is
// strict and aborts on any construct it does not understand, which is the property that makes
// this a transform rather than a transcription.
//
// Split per vendor and per task to mirror Params/Tables/, so a model's descriptor table and its
// catalog rows sit in files one `Rows` suffix apart. The suffix is not decoration: SwiftPM
// refuses two files with the same basename in one target. Every id of a single reg() group lands
// in ONE file even when the spellings disagree about the vendor prefix (`gpt-image-1` and
// `openai/gpt-image-1` are both here), which keeps the later alias collapse a local edit.
//
// One row per REGISTERED ID, not per group — aliases are still separate rows with `aliases: []`.
// displayName == id, family == "", lifecycle == .current, typicalWallClock == nil: the identity
// value of each presentation field, so nothing here pretends to know a display name or a family.

import Foundation

extension AIMLRegisteredModels {
    static let %s: [CatalogModel] = [
"""


def main():
    lines = open(REG, encoding="utf-8").read().split("\n")
    starts = [i for i, l in enumerate(lines) if "reg([" in l]
    if len(starts) != 121:
        raise SystemExit("ABORT: expected 121 reg() groups, found %d" % len(starts))
    # `return r` closes the registry literal; everything after it is lookup code, not data.
    tail = [i for i, l in enumerate(lines) if l.strip() == "return r" and i > starts[-1]]
    if len(tail) != 1:
        raise SystemExit("ABORT: expected exactly one `return r` after the last reg() group")
    registry_end = tail[0]

    by_file = {}
    rows = []
    for n, start in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else registry_end

        header = lines[start][lines[start].index("reg(["):]
        h = start
        while "])" not in header and h + 1 < end:
            h += 1
            header += lines[h]
        ids = [p for i, p in enumerate(header.split('"')) if i % 2 == 1]
        if not ids:
            die(start + 1, "reg() group with no ids")

        body = lines[h + 1:end]
        id_dependent = False
        for off, line in enumerate(body):
            s = strip_comment(line).strip()
            if re.match(r"^(let|var|if|guard|switch|for|while|func)\b", s):
                if s == ID_PREDICATE:
                    id_dependent = True
                else:
                    die(h + 2 + off, "unrecognised control flow or binding: %s" % s)

        text = "\n".join(strip_comment(l) for l in body)
        if text.count("AIMLModel(") != 1:
            die(start + 1, "expected exactly one AIMLModel( in the group body")
        arg_start = text.index("AIMLModel(") + len("AIMLModel(")
        depth, i = 1, arg_start
        while i < len(text) and depth:
            if text[i] == "(":
                depth += 1
            elif text[i] == ")":
                depth -= 1
            i += 1
        if depth:
            die(start + 1, "unbalanced parentheses in the AIMLModel initialiser")
        args_text = text[arg_start:i - 1].replace("\n", " ")

        group = ids[0]
        group_rows = []
        for mid in ids:
            lower = mid.lower()
            is_gpt2 = lower.endswith("gpt-image-2") if id_dependent else None
            vals = dict(DEFAULTS)
            seen = []
            for arg in split_args(args_text, start + 1, group):
                if ":" not in arg:
                    die(start + 1, "reg(%s): argument %r is not label: value" % (group, arg))
                label, raw = arg.split(":", 1)
                label = label.strip()
                if label not in FIELDS:
                    die(start + 1, "reg(%s): unknown AIMLModel field %r" % (group, label))
                seen.append(label)
                vals[label] = parse_value(raw, start + 1, group, is_gpt2)
            missing = [f for f in FIELDS if f not in seen and f not in DEFAULTS]
            if missing:
                die(start + 1, "reg(%s): AIMLModel call omits %s" % (group, ", ".join(missing)))
            if vals["id"] != "<id>":
                die(start + 1, "reg(%s): id: is not the closure argument" % group)
            vals["id"] = lower
            group_rows.append(vals)

        stem = file_stem(ids, group_rows[0]["isVideo"], start + 1)
        by_file.setdefault(stem, []).extend(group_rows)
        rows.extend(group_rows)

    ids = [r["id"] for r in rows]
    if len(ids) != len(set(ids)):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        raise SystemExit("ABORT: duplicate registered ids %s" % dupes)

    os.makedirs(OUTDIR, exist_ok=True)
    for stem in sorted(by_file):
        prop = swift_property(stem)
        vendor_rows = sorted(by_file[stem], key=lambda r: r["id"])
        out = [HEADER % (stem + ".swift", prop, prop)]
        body = []
        for r in vendor_rows:
            body.append("        CatalogModel(\n"
                        '            id: "%s",\n' % r["id"]
                        + "            aliases: [],\n"
                        + "            provider: .aimlapi,\n"
                        + '            displayName: "%s",\n' % r["id"]
                        + '            family: "",\n'
                        + "            lifecycle: .current,\n"
                        + "            typicalWallClock: nil,\n"
                        + "            isRegistered: true,\n"
                        + "            task: .%s,\n" % ("video" if r["isVideo"] else "image")
                        + "            isI2I: %s,\n" % swift_lit(r["isI2I"])
                        + "            requiresInputImage: %s,\n" % swift_lit(r["requiresInputImage"])
                        + "            supportsMask: %s,\n" % swift_lit(r["supportsMask"])
                        + "            maxInputImages: %s,\n" % swift_lit(r["maxInputImages"])
                        + "            imageInputParam: %s,\n" % swift_lit(r["imageInputParam"])
                        + "            secondImageParam: %s,\n" % swift_lit(r["secondImageParam"])
                        + "            acceptsMultiImages: %s,\n" % swift_lit(r["acceptsMultiImages"])
                        + "            acceptsBase64: %s,\n" % swift_lit(r["acceptsBase64"])
                        + "            acceptsPublicURL: %s,\n" % swift_lit(r["acceptsPublicURL"])
                        + "            acceptsBinary: %s,\n" % swift_lit(r["acceptsBinary"])
                        + "            generationEndpoint: %s,\n" % swift_lit(r["generationEndpoint"])
                        + "            pollingEndpoint: %s),\n" % swift_lit(r["pollingEndpoint"]))
        out.append("".join(body))
        out.append("    ]\n}\n")
        open(os.path.join(OUTDIR, stem + ".swift"), "w", encoding="utf-8").write("".join(out))

    roll = ["// AIMLRegisteredModels — every registered AI/ML id, as one CatalogModel row each.",
            "//",
            "// GENERATED by tools/stage3-catalog-gen/gen_catalog_rows.py. Do not hand-edit.",
            "// The rows themselves are in the %d per-vendor files beside this one, one property"
            % len(by_file),
            "// per file; this type is the single symbol they are reachable through.",
            "",
            "import Foundation",
            "",
            "enum AIMLRegisteredModels {",
            "",
            "    /// Every registered id, sorted by id. %d rows today." % len(rows),
            "    static let all: [CatalogModel] = ["]
    for stem in sorted(by_file):
        roll.append("        %s," % swift_property(stem))
    roll.append("    ].flatMap { $0 }.sorted { $0.id < $1.id }")
    roll.append("}")
    open(os.path.join(OUTDIR, "AIMLRegisteredModels.swift"), "w",
         encoding="utf-8").write("\n".join(roll) + "\n")

    print("wrote %d rows across %d vendor files plus AIMLRegisteredModels.swift in %s"
          % (len(rows), len(by_file), OUTDIR))


main()
