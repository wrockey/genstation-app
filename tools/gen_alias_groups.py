#!/usr/bin/env python3
"""Emit AliasGroups.swift from the reg([...]) groups of ModelRegistry.swift at e6401cc.

Read from the baseline commit, not the working tree: this fixture is a historical statement about
what the registry grouped, and it must stay regenerable after Task 18 deletes the file.
"""
import subprocess, sys

SRC = subprocess.run(
    ["git", "show", "e6401cc:GenStation/Catalog/ModelRegistry.swift"],
    capture_output=True, text=True, check=True).stdout
lines = SRC.split("\n")
starts = [i for i, l in enumerate(lines) if "reg([" in l]
if len(starts) != 121:
    sys.exit("ABORT: expected 121 reg() groups at e6401cc, found %d" % len(starts))

groups = []
for n, s in enumerate(starts):
    end = starts[n + 1] if n + 1 < len(starts) else len(lines)
    header, he = lines[s][lines[s].index("reg(["):], s
    while "])" not in header and he + 1 < end:
        he += 1
        header += lines[he]
    ids = [p.lower() for i, p in enumerate(header.split('"')) if i % 2 == 1]
    if not ids:
        sys.exit("ABORT: reg() block at line %d yielded no ids" % (s + 1))
    groups.append(ids)

# The one id-dependent builder: ModelRegistry.swift:1876 binds
#   let isGPTImage2 = id.lowercased().hasSuffix("gpt-image-2")
# and :1878/:1883 branch on it for isI2I, maxInputImages and supportsMask. Its five ids are two
# models, not one, so the group splits here. Order INSIDE each half stays reg() literal order,
# because Task 11's tie-break rule reads it.
SPLIT = ["gpt-image-1.5", "openai/gpt-image-1.5", "openai/gpt-image-1-5",
         "gpt-image-2", "openai/gpt-image-2"]
if SPLIT not in groups:
    sys.exit("ABORT: the gpt-image group is not the shape this script was written against")
groups.remove(SPLIT)
groups.append(["gpt-image-1.5", "openai/gpt-image-1.5", "openai/gpt-image-1-5"])
groups.append(["gpt-image-2", "openai/gpt-image-2"])

groups.sort(key=lambda g: g[0])
flat = [i for g in groups for i in g]
if len(flat) != len(set(flat)):
    sys.exit("ABORT: an id appears in two groups")

out = ['// The `reg([...])` groups of `ModelRegistry.swift` as recorded at `e6401cc`, the Stage 3',
       '// baseline commit — the only checked-in statement of which registered ids are spellings of',
       '// the same model. `AliasEquivalenceTests` uses it to prove every alias\'s golden fixtures are',
       '// identical to its group-mates\', which is what licenses Task 11 treating them as',
       '// interchangeable and Task 22 subtracting a deleted id\'s rows.',
       '//',
       '// Element 0 is NOT the canonical id. Order inside a group is the order of the `reg([...])`',
       '// literal, preserved deliberately: Task 11 breaks ties on it. Task 11 chooses canonicals.',
       '//',
       '// The gpt-image group is split in two: `ModelRegistry.swift:1876` binds',
       '// `let isGPTImage2 = id.lowercased().hasSuffix("gpt-image-2")` and `:1878`/`:1883` branch on it',
       '// for `isI2I`, `maxInputImages` and `supportsMask`, so those five ids are two models. Their',
       '// descriptor table is shared, which is why the fixtures agree anyway — and why nothing in',
       '// AliasEquivalenceTests would have caught a merge. Task 11 has a separate mechanical guard.',
       '//',
       '// GENERATED by tools/gen_alias_groups.py. Do not hand-edit.',
       '',
       'enum AliasGroups {', '',
       '    /// Every registered id, partitioned by model. %d groups over %d ids.' % (len(groups), len(flat)),
       '    static let groups: [[String]] = [']
for g in groups:
    out.append("        [" + ", ".join('"%s"' % i for i in g) + "],")
out += ["    ]", "}", ""]
print("\n".join(out), end="")
