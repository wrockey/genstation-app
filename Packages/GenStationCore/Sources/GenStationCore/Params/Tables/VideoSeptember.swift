import Foundation

extension ParamCatalog {
    private static func videoChoice(_ key: String, _ field: ParamField, _ label: String,
                                    _ values: [String], default value: String,
                                    help: String? = nil, when: Condition? = nil) -> ParamDescriptor {
        ParamDescriptor(wireKey: key, field: field, label: label, help: help,
            control: .picker(options: values.map(ParamValue.string), style: .menu),
            defaultValue: .string(value), visibleWhen: when, alwaysEmit: true,
            parseFallback: .value(.string(value)), allowedValues: values.map(ParamValue.string))
    }
    private static func videoDuration(_ range: ClosedRange<Int>) -> ParamDescriptor {
        ParamDescriptor(wireKey: "duration", field: .duration, label: "Duration (seconds)",
            help: "Longer videos cost more. Start with a short clip when testing a prompt.",
            control: .picker(options: range.map(ParamValue.int), style: .menu), defaultValue: .int(5),
            visibleWhen: nil, alwaysEmit: true, parseFallback: .value(.int(5)),
            allowedValues: range.map(ParamValue.int))
    }
    private static let videoAudio = ParamDescriptor(wireKey: "generate_audio", field: .generateAudio,
        label: "Generate Audio", help: "Describe dialogue, ambience, and sound effects in your prompt.",
        control: .toggle, defaultValue: .bool(true), visibleWhen: nil, alwaysEmit: true,
        parseFallback: .value(.bool(true)))
    private static let videoSeed = ParamDescriptor(wireKey: "seed", field: .seed, label: "Seed",
        help: "Leave empty for variation. A fixed seed may improve repeatability; identical output is not guaranteed.",
        control: .seed(range: 0...Int(Int32.max)), defaultValue: nil, visibleWhen: nil, alwaysEmit: false,
        parseFallback: .setNil)
    private static let videoWatermark = ParamDescriptor(wireKey: "watermark", field: .watermark,
        label: "Watermark", help: "Request the provider's watermark on the output.", control: .toggle,
        defaultValue: .bool(false), visibleWhen: nil, alwaysEmit: true, parseFallback: .value(.bool(false)))

    static let wan30Video: [ParamDescriptor] = [
        .info(label: "Wan 3.0 · Text or First/Last Frames", text: "Use a prompt alone, one starting frame, or two frames for a start and finish. Frame images require public HTTPS URLs through your configured image upload service."),
        videoChoice("resolution", .resolution, "Resolution", ["480p", "720p", "1080p"], default: "480p"),
        videoDuration(2...30),
        videoChoice("aspect_ratio", .aspectRatio, "Aspect Ratio", ["adaptive", "16:9", "4:3", "1:1", "3:4", "9:16"], default: "16:9", help: "Adaptive lets the model choose the output framing."),
        videoAudio, videoSeed, videoWatermark,
    ]
    static let seedance25Video: [ParamDescriptor] = [
        .info(label: "Seedance 2.5 · Text or First/Last Frames", text: "Use up to two images: first frame, then optional last frame. Image inputs determine the aspect ratio. The current provider rejects reference images containing real people; use another model for those inputs."),
        videoChoice("resolution", .resolution, "Resolution", ["480p", "720p"], default: "480p"),
        videoDuration(4...30),
        videoChoice("aspect_ratio", .aspectRatio, "Aspect Ratio", ["21:9", "16:9", "4:3", "1:1", "3:4", "9:16"], default: "16:9", when: .hasNoInputImages),
        videoAudio, videoSeed, videoWatermark,
    ]
    static let minimaxH3MaxVideo: [ParamDescriptor] = [
        .info(label: "MiniMax H3 Max · Text or First/Last Frames", text: "Use up to two frame images. Images must be JPEG or PNG, under 20 MB, with a short side greater than 300 pixels and aspect ratio between 2:5 and 5:2. Audio is generated by the model; this endpoint has no audio-off control."),
        videoChoice("resolution", .resolution, "Resolution", ["480p", "768p"], default: "480p"),
        videoDuration(5...15),
        videoChoice("ratio", .aspectRatio, "Aspect Ratio", ["21:9", "16:9", "4:3", "1:1", "3:4", "9:16"], default: "16:9", help: "Frame images determine the aspect ratio when supplied.", when: .hasNoInputImages),
        videoChoice("prompt_expansion_mode", .promptExpansionMode, "Prompt Expansion", ["balanced", "quality"], default: "balanced", help: "Quality spends more time elaborating the prompt; balanced starts faster."),
        videoSeed,
    ]
}
